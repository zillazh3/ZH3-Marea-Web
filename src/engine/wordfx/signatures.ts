export function fallbackSignature(
  categories: readonly string[],
  vector: readonly number[],
): MotionSignature {
  const val = vector[0] ?? 0;
  const aro = vector[1] ?? 0;
  const gra = vector[2] ?? 0;
  const tem = vector[3] ?? 0;
  const fra = vector[4] ?? 0;
  const blu = vector[5] ?? 0;

  let waveform = 'sine';
  let axis = 'y';
  const softness = 1.15 - 0.55 * aro + 0.25 * blu;
  if (aro >= 0.7 && gra < 0) {
    waveform = 'step';
    axis = 'x';
  } else if (aro >= 0.7 && tem >= 0.4) {
    waveform = 'flicker';
  } else if (gra <= -0.4 && val > 0.3) {
    waveform = 'orbit';
  } else if (val >= 0.4 && aro < 0.5) {
    waveform = 'breath';
    axis = 'scale';
  }
  const releaseMs = val < -0.2 || blu > 0.4 ? 850 : aro >= 0.7 ? 450 : 650;
  const residueLevel = val < -0.2 || val > 0.5 ? 0.22 : 0.14;
  const zeta = categories.some((c) => c === 'joy' || c === 'love' || c === 'tenderness') ? 0.84 : 1;

  return ms({
    waveform,
    freqRangeHz: [0.5 + 0.45 * aro, 0.9 + 1.0 * aro],
    axis,
    ampRangeEm: [0.01 + 0.01 * aro, 0.02 + 0.016 * aro],
    glowSpread: Math.min(0.8, Math.max(0.15, 0.25 + 0.3 * Math.max(0, val))),
    fillEdgeSoftness: Math.min(1.5, Math.max(0.45, softness)),
    fillTint: Math.min(0.6, Math.max(0.25, 0.35 + 0.2 * Math.abs(val))),
    particleKind: val > 0.4 ? 'spark' : fra > 0.6 ? 'dust' : 'none',
    particleMax: val > 0.4 || fra > 0.6 ? 6 : 0,
    releaseMs,
    residueLevel,
    zeta,
  });
}

export function signatureFor(
  categories: readonly string[],
  vector: readonly number[],
  weights?: readonly number[],
): MotionSignature {
  if (categories.length === 0) return fallbackSignature([], vector);
  const sigs = categories.map((c) => SIGNATURES[c] ?? fallbackSignature([c], vector));
  if (sigs.length === 1 && sigs[0]) return sigs[0];

  const rawWs = weights ? [...weights] : sigs.map((_, i) => 1 / (i + 1));
  const tot = rawWs.reduce((a, b) => a + b, 0) || 1;
  const ws = rawWs.map((w) => w / tot);

  let leadIdx = 0;
  for (let i = 1; i < ws.length; i += 1) {
    if ((ws[i] ?? 0) > (ws[leadIdx] ?? 0)) leadIdx = i;
  }
  const lead = sigs[leadIdx] ?? DEFAULT_SIG;

  const avg = (pick: (s: MotionSignature) => number): number =>
    sigs.reduce((acc, s, i) => acc + (ws[i] ?? 0) * pick(s), 0);

  return {
    waveform: lead.waveform,
    freqRangeHz: [avg((s) => s.freqRangeHz[0]), avg((s) => s.freqRangeHz[1])],
    axis: lead.axis,
    ampRangeEm: [avg((s) => s.ampRangeEm[0]), avg((s) => s.ampRangeEm[1])],
    glowSpread: avg((s) => s.glowSpread),
    glowColor: lead.glowColor,
    fillEdgeSoftness: avg((s) => s.fillEdgeSoftness),
    fillTint: Math.min(
      0.6,
      Math.max(
        0.25,
        avg((s) => s.fillTint),
      ),
    ),
    particleKind: lead.particleKind,
    particleMax: pyRound(avg((s) => s.particleMax)),
    sparkleStyle: lead.sparkleStyle,
    releaseMs: avg((s) => s.releaseMs),
    residueLevel: avg((s) => s.residueLevel),
    zeta: avg((s) => s.zeta),
    motif: lead.motif,
    tintSpread: lead.tintSpread,
    scatterEm: lead.scatterEm,
    glitch: lead.glitch,
    shimmer: lead.shimmer,
  };
}

export function evalWaveform(
  waveform: string,
  t: number,
  freqHz: number,
  letterIdx: number,
  seedU = 0,
  beatPhase?: number,
  age?: number,
): number {
  const ph = 2 * Math.PI * (freqHz * t + seedU) - 0.65 * letterIdx;
  if (waveform === 'sine') return Math.sin(ph);
  if (waveform === 'heartbeat') {
    const a = (age ?? t) - 0.05 * letterIdx;
    let u = a * freqHz;
    if (u < 0 || u >= 2) return 0;
    u = pyMod(u, 1);
    return Math.exp(-(((u - 0.14) / 0.07) ** 2)) + 0.6 * Math.exp(-(((u - 0.36) / 0.08) ** 2));
  }
  if (waveform === 'shake') {
    const a = (age ?? t) - 0.02 * letterIdx;
    return a >= 0
      ? Math.exp(-Math.max(0, a) / 0.14) * Math.sin(2 * Math.PI * freqHz * a + 1.7 * seedU)
      : 0;
  }
  if (waveform === 'breath') {
    const u = pyMod(freqHz * t + seedU - 0.12 * letterIdx, 1);
    return Math.exp(-(((u - 0.18) / 0.11) ** 2)) + 0.65 * Math.exp(-(((u - 0.42) / 0.13) ** 2));
  }
  if (waveform === 'tick') {
    const u = pyMod((beatPhase ?? freqHz * t) - 0.06 * letterIdx, 1);
    return Math.exp(-(((u - 0.08) / 0.07) ** 2)) * 2 - 0.3;
  }
  if (waveform === 'step') return Math.tanh(2.5 * Math.sin(ph));
  if (waveform === 'flicker') {
    return 0.65 * Math.sin(ph * 1.7) + 0.35 * Math.sin(ph * 3.1 + 1.3 * letterIdx);
  }
  if (waveform === 'erode') return -0.5 * (1 - Math.cos(Math.min(Math.PI, Math.max(0, ph * 0.25))));
  if (waveform === 'pendulum') return Math.sin(ph) + 0.12 * Math.sin(3 * ph);
  if (waveform === 'surge') return Math.sin(ph + 0.38 * Math.sin(ph));
  if (waveform === 'shimmer') {
    return 0.62 * Math.sin(ph * 1.45) + 0.38 * Math.cos(ph * 2.35 + 0.85 * letterIdx);
  }
  return Math.sin(ph);
}
